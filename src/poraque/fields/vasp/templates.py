def _render(tags, comments, extra):
    """Lay out ``TAG = VALUE  # comment`` lines, aligned."""
    values = dict(tags)
    order = [name for name, _ in tags]
    for name, value in (extra or {}).items():
        name = str(name).upper()
        if name not in values:
            order.append(name)
        values[name] = value

    width = max(len(name) for name in order)
    lines = []
    for name in order:
        line = f"{name:<{width}} = {values[name]}"
        note = comments.get(name)
        lines.append(f"{line}  # {note}" if note else line)
    return "\n".join(lines) + "\n"


def _as_segments(path):
    """Accept either explicit segments or a flat continuous path."""
    path = list(path)
    if path and len(path[0]) == 2 and not _is_point(path[0]):
        return [(tuple(start), tuple(end)) for start, end in path]
    points = [tuple(point) for point in path]
    return list(zip(points, points[1:]))


def _is_point(candidate):
    """Whether ``candidate`` is a k-point rather than a pair of them."""
    return all(isinstance(value, (int, float)) for value in candidate)
